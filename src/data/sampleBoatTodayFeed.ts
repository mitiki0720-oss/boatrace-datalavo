type RacerSeed = {
	name: string;
	branch: string;
	class: string;
	averageStart: string;
	winRate: string;
	secondRate: string;
	motorNo: string;
	motorSecondRate: string;
	boatMotorNo: string;
	boatSecondRate: string;
};

const createRacers = (boatNumbers: string[], seeds: RacerSeed[]): BoatRacerItem[] =>
	seeds.map((seed, index) => ({
		frameNo: (index + 1) as 1 | 2 | 3 | 4 | 5 | 6,
		boatNo: boatNumbers[index],
		name: seed.name,
		branch: seed.branch,
		class: seed.class,
		averageStart: seed.averageStart,
		winRate: seed.winRate,
		secondRate: seed.secondRate,
		motorNo: seed.motorNo,
		motorSecondRate: seed.motorSecondRate,
		boatMotorNo: seed.boatMotorNo,
		boatSecondRate: seed.boatSecondRate,
	}));

const createExhibitions = (
	items: Array<{
		exhibitionTime: string;
		tilt: string;
		startTiming: string;
		course: string;
		evaluation: "good" | "normal" | "bad" | "unknown";
		memo: string;
	}>,
): BoatExhibitionItem[] =>
	items.map((item, index) => ({
		frameNo: (index + 1) as 1 | 2 | 3 | 4 | 5 | 6,
		exhibitionTime: item.exhibitionTime,
		tilt: item.tilt,
		startTiming: item.startTiming,
		course: item.course,
		evaluation: item.evaluation,
		memo: item.memo,
	}));

